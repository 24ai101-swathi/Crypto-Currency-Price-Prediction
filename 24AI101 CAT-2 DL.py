import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout
df = pd.read_csv('/content/coin_Bitcoin.csv')
print("Original dataset shape:", df.shape)
df['Date'] = pd.to_datetime(df['Date'])
df = df.sort_values('Date').reset_index(drop=True)
df_subset = df.tail(2000).copy()
print("Subset shape:", df_subset.shape)
if df_subset.isnull().sum().sum() > 0:
    df_subset = df_subset.fillna(method='ffill').fillna(method='bfill')
scaler = MinMaxScaler(feature_range=(0, 1))
scaled_close = scaler.fit_transform(df_subset[['Close']])
def create_dataset(dataset, look_back=7):
    X, Y = [], []
    for i in range(len(dataset) - look_back):
        X.append(dataset[i:(i + look_back), 0])
        Y.append(dataset[i + look_back, 0])
    return np.array(X), np.array(Y)
look_back = 7
X, y = create_dataset(scaled_close, look_back)
X = np.reshape(X, (X.shape[0], X.shape[1], 1))
train_size = int(len(X) * 0.80)
test_size = len(X) - train_size
X_train, X_test = X[0:train_size], X[train_size:len(X)]
y_train, y_test = y[0:train_size], y[train_size:len(y)]
print(f"Train shape: {X_train.shape}, Test shape: {X_test.shape}")
model = Sequential([
    LSTM(50, return_sequences=True, input_shape=(look_back, 1)),
    Dropout(0.2),
    LSTM(50, return_sequences=False),
    Dropout(0.2),
    Dense(25),
    Dense(1)
])
model.compile(optimizer='adam', loss='mean_squared_error')
model.summary()
history = model.fit(X_train, y_train, batch_size=32, epochs=7, validation_data=(X_test, y_test), verbose=1)
predictions = model.predict(X_test)
predictions_unscaled = scaler.inverse_transform(predictions)
y_test_unscaled = scaler.inverse_transform(y_test.reshape(-1, 1))
mae = mean_absolute_error(y_test_unscaled, predictions_unscaled)
rmse = np.sqrt(mean_squared_error(y_test_unscaled, predictions_unscaled))
print(f"\nEvaluation Metrics on Test Data:")
print(f"Mean Absolute Error (MAE): ${mae:.2f}")
print(f"Root Mean Squared Error (RMSE): ${rmse:.2f}")
plt.figure(figsize=(14, 7))
plt.plot(df_subset['Date'].iloc[train_size + look_back:].values, y_test_unscaled, label='Actual Bitcoin Price', color='blue')
plt.plot(df_subset['Date'].iloc[train_size + look_back:].values, predictions_unscaled, label='Predicted Bitcoin Price', color='red')
plt.title('Bitcoin Closing Price Prediction (LSTM)')
plt.xlabel('Date')
plt.ylabel('Price in USD')
plt.legend()
plt.grid(True)
plt.show()